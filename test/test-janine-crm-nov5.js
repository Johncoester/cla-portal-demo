/* Janine CRM follow-ups. Fake data only. Pin still defaults on. Due colors include the day count. Blank activity is not invented. */
import { readFileSync } from 'node:fs';
import { createMockAdapter } from '../js/data/mock-adapter.js';
import { crmFilter, daysBetween, daysOverdue, dueTone, inLocalRange } from '../js/data/crm.js';
const mem = () => { const m = new Map(); return { getItem: (k) => (m.has(k) ? m.get(k) : null), setItem: (k, v) => m.set(k, String(v)), removeItem: (k) => m.delete(k) }; };
let fail = 0;
const ok = (c, m) => { if (c) console.log('ok', m); else { fail++; console.log('FAIL', m); } };
ok(daysBetween('2026-11-01', '2026-11-06') === 5, 'five calendar days');
ok(daysOverdue('2026-11-01', '2026-11-06') === 5 && daysOverdue('2026-11-06', '2026-11-06') === 0 && daysOverdue('', '2026-11-06') === 0, 'overdue count is zero for today and for a blank date');
ok(dueTone('2026-11-01', '2026-11-06', true) === 'overdue' && dueTone('2026-11-06', '2026-11-06', true) === 'today' && dueTone('2026-11-09', '2026-11-06', true) === 'future', 'open tasks are red, yellow, or green by the local day');
ok(dueTone('2026-11-01', '2026-11-06', false) === 'none' && dueTone('', '2026-11-06', true) === 'none', 'completed and undated tasks have no due color');
ok(inLocalRange('', '2026-11-01', '2026-11-06') === false && inLocalRange('2026-11-03T15:00:00Z', '2026-11-01', '2026-11-06') === true, 'a blank timestamp does not pass a date filter');
const rows = [{ id: 'a', name: 'A', createdAt: '2026-11-01T12:00:00Z', modifiedAt: null, lastActivityAt: null }];
ok(crmFilter(rows, { createdFrom: '2026-11-01', createdTo: '2026-11-01' }).length === 1, 'created time uses the stored day');
ok(crmFilter(rows, { activityFrom: '2026-11-01' }).length === 0, 'a missing last activity time is not treated as the created time');
const pin = readFileSync(new URL('../js/pages/crm-views.js', import.meta.url), 'utf8');
ok(/name="pin" checked/.test(pin), 'the pin checkbox still starts checked');
const store = mem();
const api = createMockAdapter({ storage: store, sessionStorage: mem() });
await api.signInDev('u-admin');
const leads = await api.listCrmLeads();
ok(leads.length > 0 && leads.every((l) => l.lastActivityAt == null || l.lastActivityAt !== l.createdAt || true), 'leads load');
ok(leads.some((l) => l.lastActivityAt == null) && leads.every((l) => l.lastActivityAt !== l.createdAt), 'last activity stays blank when the lead has no activity or email');
const tasks = await api.listCrmTasks();
const openLate = tasks.filter((t) => t.open && t.dueDate && t.dueDate < '2026-11-06');
ok(openLate.length > 0, 'the fake home list has an open task before today');
const view = await api.createCrmView({ module: 'leads', name: 'Janine pin check', criteria: [] });
ok(view.pinned === true, 'a new view still pins unless pin is explicitly false');
const unpinned = await api.createCrmView({ module: 'leads', name: 'Janine unpinned', criteria: [], pin: false });
ok(unpinned.pinned === false, 'pin false stays unpinned');
await api.pinCrmView(view.id, false);
const after = (await api.listCrmViews('leads')).find((v) => v.id === view.id);
ok(after && after.pinned === false, 'unpin keeps the view and only removes the pin');
await api.retireCrmView(view.id);
ok(!(await api.listCrmViews('leads')).some((v) => v.id === view.id), 'delete removes the view definition');
ok((await api.listCrmLeads()).length === leads.length, 'deleting a view does not delete leads');
await api.signInDev('u-proc');
let refused = false;
try { const mine = await api.listCrmTasks(); const t = mine.find((z) => z.open); await api.closeCrmTask(t.id); } catch (e) { refused = /CLA staff only/.test(e.message); }
ok(refused, 'a processor cannot close a CRM task');
console.log(fail ? fail + ' failed' : 'janine crm passed');
if (fail) process.exit(1);
