/* Save a file with no Processor. Fake people only. A blank Processor is Unassigned, never the signed-in person. */
import { createMockAdapter } from '../js/data/mock-adapter.js';
import { processorChoices, PROCESSOR_PICK_ROLES } from '../js/data/place-order.js';
const mem = () => { const m = new Map(); return { getItem: (k) => (m.has(k) ? m.get(k) : null), setItem: (k, v) => m.set(k, String(v)), removeItem: (k) => m.delete(k) }; };
let fail = 0;
const ok = (c, m) => { if (c) console.log('ok', m); else { fail++; console.log('FAIL', m); } };
const rejects = async (p, re) => { try { await p(); return false; } catch (e) { return !re || re.test(e.message); } };
const ORDER = { street: '9 Unassigned Lane', city: 'Rockville', state: 'MD', zip: '20850', openDate: '2026-11-01' };
const choices = processorChoices([{ id: 'u-new', firstName: 'Nina', lastName: 'New', role: 'Processor' }], 'u-old', 'u-admin');
ok(choices.options[0].label === 'Unassigned' && choices.dropped && choices.value === '', 'a Processor who is not on the list is dropped and nobody is invented');
ok(processorChoices([{ id: 'u-new', firstName: 'Nina', lastName: 'New', role: 'Processor' }], 'u-new', 'u-new').value === 'u-new', 'a Processor who is still eligible stays selected');

const store = mem();
const a = createMockAdapter({ storage: store, sessionStorage: mem() });
await a.signInDev('u-admin');
const before = (await a.listProcessors()).map((p) => p.id);
const made = await a.adminCreateUser({ firstName: 'Nina', lastName: 'Newproc', email: 'nina.newproc@example.test', role: 'Processor' });
const after = await a.listProcessors();
ok(!before.includes(made.id) && after.some((p) => p.id === made.id), 'a Processor created after the list was loaded is returned by the next refresh');
const saved = await a.createDeal({ ...ORDER, processorId: '' });
ok(!saved.processorId && saved.processorName === 'Unassigned', 'an Admin saves the file with no Processor');
ok(!(await a.getDeal(saved.id)).participants.some((p) => p.role === 'Processor'), 'no Processor participant is invented');
const again = await a.getDeal(saved.id);
ok(!again.processorId && again.street === '9 Unassigned Lane', 'reopening the file keeps it Unassigned');
const assigned = await a.updateDeal(saved.id, { processorId: made.id, street: '9 Unassigned Lane' });
ok(assigned.processorId === made.id && assigned.street === '9 Unassigned Lane', 'the new Processor can be assigned later without changing the address');
ok(await rejects(() => a.updateDeal(saved.id, { processorId: 'u-sp' }), /Processor, Preprocessor, Admin or Super admin/), 'a salesperson cannot be the Processor');
ok(await rejects(() => a.signInDev('u-buyer').then(() => a.createDeal(ORDER)), /Processor or Admin/), 'an outside user cannot save a file');

const raw = JSON.parse(store.getItem('cla-portal-new:data:v30'));
raw.profiles.find((p) => p.id === 'u-proc').isDemo = true;
raw.profiles.find((p) => p.id === 'u-admin').isDemo = false;
store.setItem('cla-portal-new:data:v30', JSON.stringify(raw));
const real = createMockAdapter({ storage: store, sessionStorage: mem() });
await real.signInDev('u-admin');
ok(!(await real.listProcessors()).some((p) => p.id === 'u-proc'), 'a real login does not see a demo Processor');
ok(await rejects(() => real.updateDeal(saved.id, { processorId: 'u-proc' }), /demo Processor/), 'a real file rejects a demo Processor');
raw.profiles.find((p) => p.id === 'u-admin').isDemo = true;
raw.profiles.find((p) => p.id === 'u-preproc').isDemo = true;
store.setItem('cla-portal-new:data:v30', JSON.stringify(raw));
const demo = createMockAdapter({ storage: store, sessionStorage: mem() });
await demo.signInDev('u-admin');
const demoFile = await demo.createDeal({ ...ORDER, street: '2 Demo Unassigned', processorId: '' });
ok(!demoFile.processorId, 'a demo login can also save with no Processor');
ok(await rejects(() => demo.updateDeal(demoFile.id, { processorId: 'u-sp' }), /Processor, Preprocessor, Admin or Super admin/), 'a demo file still rejects a salesperson');
const demoAssigned = await demo.updateDeal(demoFile.id, { processorId: 'u-preproc' });
ok(demoAssigned.processorId === 'u-preproc', 'a demo file can take a demo Processor');
ok(PROCESSOR_PICK_ROLES.includes('Processor') && !PROCESSOR_PICK_ROLES.includes('Sales Person'), 'the eligible roles are unchanged');
console.log(fail ? fail + ' failed' : 'unassigned processor passed');
if (fail) process.exit(1);
